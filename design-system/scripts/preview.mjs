// Generates dist/preview.html: a one-page visual reference of every token.
// Called by build.mjs. Works offline, on desktop and on a phone.

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const data = JSON.parse(await readFile(join(root, 'dist/json/tokens.json'), 'utf8'))

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
const by = (prefix) => data.tokens.filter((t) => t.name.startsWith(prefix + '.'))
const v = (t) => `var(${t.cssVar})`

const swatches = (tokens) =>
  tokens
    .map(
      (t) => `<li class="sw"><span class="chip" style="background:${v(t)}"></span>
        <b>${esc(t.name)}</b><code>${esc(t.resolved)}</code>${t.description ? `<small>${esc(t.description)}</small>` : ''}</li>`
    )
    .join('')

const semantic = data.themes.light
  .map(
    (t) => `<li class="sw"><span class="chip" style="background:${v(t)}"></span>
      <b>${esc(t.name)}</b><code>${esc(t.cssVar)}</code>${t.description ? `<small>${esc(t.description)}</small>` : ''}</li>`
  )
  .join('')

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Mannheim Feed design tokens v${esc(data.version)}</title>
<link rel="stylesheet" href="css/tokens.css">
<link href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,400..800&display=swap" rel="stylesheet">
<style>
  body { margin: 0; background: var(--mf-color-bg-page); color: var(--mf-color-text-primary);
         font: var(--mf-font-size-body)/var(--mf-font-line-height-base) var(--mf-font-family-sans); }
  main { max-width: 860px; margin: 0 auto; padding: var(--mf-space-4) var(--mf-space-4) var(--mf-space-12); }
  h1 { font-size: var(--mf-font-size-headline); font-weight: var(--mf-font-weight-heavy); font-stretch: var(--mf-font-stretch-expanded); letter-spacing: var(--mf-font-letter-spacing-tight); margin: var(--mf-space-4) 0 var(--mf-space-1); }
  h2 { font-size: var(--mf-font-size-title); margin: var(--mf-space-10) 0 var(--mf-space-3); padding-top: var(--mf-space-4); border-top: 1px solid var(--mf-color-border-default); }
  p, small { color: var(--mf-color-text-secondary); }
  code { font: 0.8rem ui-monospace, Menlo, monospace; color: var(--mf-color-text-secondary); }
  ul { list-style: none; padding: 0; margin: 0; display: grid; gap: var(--mf-space-3); grid-template-columns: repeat(auto-fill, minmax(230px, 1fr)); }
  .sw { display: grid; grid-template-columns: 44px 1fr; column-gap: var(--mf-space-3); align-items: center; }
  .sw .chip { grid-row: span 3; width: 44px; height: 44px; border-radius: var(--mf-radius-md); border: 1px solid var(--mf-color-border-default); }
  .sw small { grid-column: 2; }
  .toggle { position: sticky; top: var(--mf-space-2); float: right; z-index: var(--mf-z-sticky); }
  .row { display: flex; flex-wrap: wrap; gap: var(--mf-space-3); align-items: center; }
  .bar { height: 16px; background: var(--mf-color-accent-default); border-radius: var(--mf-radius-xs); }
  .box { width: 64px; height: 64px; background: var(--mf-color-bg-surface); border: 1px solid var(--mf-color-border-default); display: grid; place-items: center; font-size: var(--mf-font-size-caption); color: var(--mf-color-text-secondary); }
  .btn { min-height: var(--mf-button-min-height); padding: var(--mf-button-padding-y) var(--mf-button-padding-x); border-radius: var(--mf-button-radius); border: 1px solid var(--mf-color-border-default); background: var(--mf-color-bg-surface); color: var(--mf-color-text-primary); font: inherit; font-weight: var(--mf-button-font-weight); }
  .btn.primary { background: var(--mf-color-accent-default); border-color: var(--mf-color-accent-default); color: var(--mf-color-text-on-accent); }
  .tag { display: inline-flex; align-items: center; min-height: var(--mf-chip-min-height); padding: var(--mf-chip-padding-y) var(--mf-chip-padding-x); border-radius: var(--mf-chip-radius); border: 1px solid var(--mf-color-border-default); background: var(--mf-color-bg-surface); }
  .input { min-height: var(--mf-input-min-height); padding: var(--mf-input-padding-y) var(--mf-input-padding-x); border-radius: var(--mf-input-radius); border: 1px solid var(--mf-color-border-default); background: var(--mf-color-bg-surface); color: inherit; font: inherit; }
  .t { margin: var(--mf-space-1) 0; }
</style>
</head>
<body>
<main>
  <button class="btn toggle" id="theme" type="button">Theme: system</button>
  <h1>Mannheim Feed design tokens</h1>
  <p>Version ${esc(data.version)} · ${data.tokens.length} tokens · generated from <code>design-system/tokens/</code>. Do not edit this file by hand.</p>

  <h2>Semantic colours (use these in the app; they change with the theme)</h2>
  <ul>${semantic}</ul>

  <h2>Core palette (raw values, never used directly in components)</h2>
  <ul>${swatches(by('color'))}</ul>

  <h2>Typography</h2>
  ${by('font.size')
    .map((t) => `<p class="t" style="font-size:${v(t)};color:var(--mf-color-text-primary)">${esc(t.name.split('.').pop())} <code>${esc(t.resolved)}</code> — Neues aus Mannheim</p>`)
    .join('')}
  <p class="t" style="font-weight:var(--mf-font-weight-heavy);font-stretch:var(--mf-font-stretch-wide);color:var(--mf-color-text-primary)">Heavy + wide (brand) — Mannheim Feed</p>
  <p class="t" style="font-weight:var(--mf-font-weight-bold);font-stretch:var(--mf-font-stretch-condensed);color:var(--mf-color-text-primary)">Bold + condensed (article titles) — Stadtrat beschließt neuen Haushalt</p>

  <h2>Spacing (4px grid)</h2>
  ${by('space')
    .map((t) => `<div class="row"><code style="width:7ch">${esc(t.name)}</code><div class="bar" style="width:${v(t)};min-width:2px"></div><code>${esc(t.resolved)}</code></div>`)
    .join('')}

  <h2>Radius</h2>
  <div class="row">${by('radius')
    .map((t) => `<div><div class="box" style="border-radius:${v(t)}"></div><code>${esc(t.name.split('.').pop())}<br>${esc(t.resolved)}</code></div>`)
    .join('')}</div>

  <h2>Shadow</h2>
  <div class="row">${by('shadow')
    .map((t) => `<div><div class="box" style="box-shadow:${v(t)}"></div><code>${esc(t.name.split('.').pop())}</code></div>`)
    .join('')}</div>

  <h2>Components (built only from tokens)</h2>
  <div class="row">
    <button class="btn" type="button">Button</button>
    <button class="btn primary" type="button">Primary</button>
    <span class="tag">Chip</span>
    <input class="input" placeholder="Input" aria-label="Input example">
  </div>
</main>
<script>
  const modes = [null, 'light', 'dark'], label = ['system', 'light', 'dark'];
  let i = 0; const b = document.getElementById('theme');
  b.addEventListener('click', () => {
    i = (i + 1) % 3;
    modes[i] ? document.documentElement.dataset.theme = modes[i] : delete document.documentElement.dataset.theme;
    b.textContent = 'Theme: ' + label[i];
  });
</script>
</body>
</html>
`

await writeFile(join(root, 'dist/preview.html'), html)
