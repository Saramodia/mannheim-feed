// Builds the design tokens into files the apps can use.
//
//   tokens/**/*.json  (source of truth, W3C DTCG format)
//        │
//        ▼  Style Dictionary
//   dist/css/tokens.css   CSS custom properties, light + dark
//   dist/ts/tokens.ts     typed constants for TypeScript code
//   dist/json/tokens.json flat list for other tools (Figma, native apps, docs)
//
// Run:  npm run build   (inside design-system/)

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')
const PREFIX = 'mf'

const { version } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

// font-stretch needs a % sign; Style Dictionary does not know that unit.
StyleDictionary.registerTransform({
  name: 'mf/font-stretch-percent',
  type: 'value',
  filter: (token) => token.path[0] === 'font' && token.path[1] === 'stretch',
  transform: (token) => `${token.$value ?? token.value}%`
})
StyleDictionary.registerTransform({
  name: 'mf/z-unitless',
  type: 'value',
  filter: (token) => token.path[0] === 'z',
  transform: (token) => String(token.$value ?? token.value)
})
StyleDictionary.registerTransformGroup({
  name: 'mf/css',
  transforms: [...StyleDictionary.hooks.transformGroups.css, 'mf/font-stretch-percent', 'mf/z-unitless']
})

function make(source, { filter, selector }) {
  return new StyleDictionary({
    // Dark only outputs semantic colours that point at core colours living in :root
    // (the base build). Style Dictionary warns about that on purpose, so downgrade it.
    log: { verbosity: 'silent', warnings: filter ? 'disabled' : 'error' },
    source: source.map((p) => join(root, p)),
    platforms: {
      css: {
        prefix: PREFIX,
        transformGroup: 'mf/css',
        buildPath: join(dist, 'tmp/'),
        files: [
          {
            destination: 'out.css',
            format: 'css/variables',
            filter,
            options: { outputReferences: true, selector, fileHeader: () => [] }
          }
        ]
      }
    }
  })
}

const isSemantic = (token) => token.filePath.includes('/semantic/')

// 1. Base: everything, with the LIGHT theme as the default.
const base = make(
  ['tokens/core/*.json', 'tokens/semantic/light.json', 'tokens/component/*.json'],
  { selector: ':root' }
)
// 2. Dark: only the semantic colours that change.
const dark = make(['tokens/core/color.json', 'tokens/semantic/dark.json'], {
  filter: isSemantic,
  selector: ':root'
})

const body = async (sd) => {
  const [file] = await sd.formatPlatform('css')
  return file.output
}
const declarations = (css) => css.replace(/^[^{]*\{/, '').replace(/\}\s*$/, '').trimEnd()
const indent = (text, n) =>
  text.split('\n').map((l) => (l.trim() ? ' '.repeat(n) + l.trim() : l)).join('\n')

// Style Dictionary leaves an empty "/** */" header even when told not to; drop it,
// and declare the default colour scheme inside the base :root block.
const baseCss = (await body(base))
  .replace(/^\s*\/\*\*\s*\*\/\s*/, '')
  .replace(/\n\}\s*$/, '\n  color-scheme: light;\n}')
const darkDecl = declarations(await body(dark)).replace(/^\s*\n/, '')

const css = `/* Mannheim Feed design tokens v${version}
 * GENERATED by design-system/scripts/build.mjs. Do not edit by hand.
 * Edit the JSON files in design-system/tokens/ and run \`npm run build\`.
 */
${baseCss.trimEnd()}

/* Light is the default above. Dark follows the system... */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indent(darkDecl, 4)}
    color-scheme: dark;
  }
}
/* ...unless the app forces a theme with data-theme="dark" or "light". */
:root[data-theme="dark"] {
${indent(darkDecl, 2)}
  color-scheme: dark;
}
`

// ---- TypeScript + JSON ----
const flat = async (sd) => {
  const { allTokens } = await sd.getPlatformTokens('css')
  return allTokens
}
const baseTokens = await flat(base)
const darkTokens = (await flat(dark)).filter(isSemantic)

const record = (t) => ({
  name: t.path.join('.'),
  cssVar: `--${t.name}`,
  value: t.original.$value ?? t.original.value, // as written in the source (may be a {reference})
  resolved: t.value ?? t.$value,
  type: t.$type ?? t.type,
  description: t.$description ?? t.description ?? undefined
})
const jsonOut = {
  version,
  tokens: baseTokens.filter((t) => t.path[0] !== 'color' || !isSemantic(t)).map(record),
  themes: {
    light: baseTokens.filter(isSemantic).map(record),
    dark: darkTokens.map(record)
  }
}

const nest = (tokens) => {
  const out = {}
  for (const t of tokens) {
    let node = out
    t.path.slice(0, -1).forEach((key) => (node = node[key] ??= {}))
    node[t.path.at(-1)] = t.value ?? t.$value
  }
  return out
}
const themeObj = (tokens) => nest(tokens).color
const nonColorSemantic = baseTokens.filter((t) => !(t.path[0] === 'color' && isSemantic(t)))

const ts = `// Mannheim Feed design tokens v${version}
// GENERATED by design-system/scripts/build.mjs. Do not edit by hand.

export const version = ${JSON.stringify(version)} as const

/** Core and component tokens (they do not change with the theme). */
export const tokens = ${JSON.stringify(nest(nonColorSemantic), null, 2)} as const

/** Semantic colours per theme. */
export const themes = {
  light: ${JSON.stringify(themeObj(baseTokens.filter(isSemantic)), null, 2).replace(/\n/g, '\n  ')},
  dark: ${JSON.stringify(themeObj(darkTokens), null, 2).replace(/\n/g, '\n  ')}
} as const

export type ThemeName = keyof typeof themes
`

await mkdir(join(dist, 'css'), { recursive: true })
await mkdir(join(dist, 'ts'), { recursive: true })
await mkdir(join(dist, 'json'), { recursive: true })
await writeFile(join(dist, 'css/tokens.css'), css)
await writeFile(join(dist, 'ts/tokens.ts'), ts)
await writeFile(join(dist, 'json/tokens.json'), JSON.stringify(jsonOut, null, 2) + '\n')

const { rm } = await import('node:fs/promises')
await rm(join(dist, 'tmp'), { recursive: true, force: true })

await import('./preview.mjs') // dist/preview.html

console.log(
  `design-system v${version}: ${jsonOut.tokens.length} tokens + ${jsonOut.themes.light.length} semantic colours x 2 themes → dist/`
)
